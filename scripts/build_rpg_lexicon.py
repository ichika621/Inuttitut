# -*- coding: utf-8 -*-
"""scripts/a2_bank.py (+ a2_bank_en.py, rpg_content.py) → rpg/lexicon.js and rpg/story.js.

Every Inuttitut string the game shows comes from these two files. The build fails if a
dialogue line, reply, drill, or marked word is missing from the example bank / glossary.
Usage: python scripts/build_rpg_lexicon.py
"""
import sys, json, io, os
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import a2_bank as B
import a2_bank_en as E
import rpg_content as C

ROOT = os.path.dirname(HERE)


def lexicon():
    units, items = [], []
    for u in B.UNITS:
        en = E.UNIT_EN[u["id"]]
        units.append({"id": u["id"], "cefr": u["cefr"],
                      "title": {"en": en["title"], "ja": u["title"]},
                      "cando": {"en": en["cando"], "ja": u["cando"]},
                      "grammar": [{"h": {"en": ge[0], "ja": gj[0]}, "b": {"en": ge[1], "ja": gj[1]}} for gj, ge in zip(u["grammar"], en["grammar"])]})
        if len(u["grammar"]) != len(en["grammar"]):
            raise SystemExit("grammar count mismatch in " + u["id"])
    def note(n):
        if not n: return None
        if n not in E.NOTE_EN: raise SystemExit("missing English note: " + n)
        return {"en": E.NOTE_EN[n], "ja": n}
    for x in B.all_items():
        items.append({"id": x["id"], "unit": x["unit"], "kind": x["kind"], "inu": x["inu"], "en": x["en"], "ja": x["ja"],
                      "src": x["src"], "note": note(x["note"])})
    for u in B.UNITS:
        for i, (inu, en, ja) in enumerate(u.get("vocab", [])):
            items.append({"id": f"{u['id']}-v{i+1:02d}", "unit": u["id"], "kind": "P", "inu": inu, "en": en, "ja": ja,
                          "src": "I11", "note": note(E.VOCAB_NOTE_JA)})
    seen = set()
    for it in items:
        if it["inu"] in seen: raise SystemExit("duplicate inu: " + it["inu"])
        seen.add(it["inu"])
    return {"units": units, "items": items, "src": B.SRC,
            "kinds": {k: {"en": E.KIND_SHORT_EN[k], "ja": {"P": "授業・原文", "T": "授業・表", "R": "授業の規則", "W": "ネット"}[k]} for k in "PTRW"}}


def main():
    lex = lexicon()
    errs = C.validate({it["inu"] for it in lex["items"]})
    if errs:
        raise SystemExit("Game content check failed:\n  " + "\n  ".join(errs))
    out1 = os.path.join(ROOT, "rpg", "lexicon.js")
    io.open(out1, "w", encoding="utf-8").write(
        "// Generated by scripts/build_rpg_lexicon.py from scripts/a2_bank.py. Do not edit by hand.\n"
        "// kinds: P = printed in course handouts, T = course paradigm tables, R = built only from course forms+rules, W = web (URL in src).\n"
        "window.LEX = " + json.dumps(lex, ensure_ascii=False) + ";\n")
    out2 = os.path.join(ROOT, "rpg", "story.js")
    io.open(out2, "w", encoding="utf-8").write(
        "// Generated by scripts/build_rpg_lexicon.py from scripts/rpg_content.py. Do not edit by hand.\n"
        "window.STORY = " + json.dumps(C.export(), ensure_ascii=False) + ";\n")
    print("wrote", out1, len(lex["units"]), "units", len(lex["items"]), "items")
    print("wrote", out2, len(C.SCRIPTS), "scripts", len(C.QUESTS), "quests", len(C.GLOSSARY), "glossary entries")


if __name__ == "__main__":
    main()
